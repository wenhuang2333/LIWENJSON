#!/usr/bin/env python3
"""Gate: the committed independent-corpus report is one this build produces.

C-01 (marks/1120优化.md §6): the CI step that was supposed to check
`code/docs/EVAL_INDEPENDENT.md` ran

    git diff --exit-code -- code/docs/EVAL_INDEPENDENT.md

with `working-directory: code`, so the pathspec resolved to
`code/code/docs/EVAL_INDEPENDENT.md` -- a path that does not exist. `git diff`
is green for an untracked or non-existent path, so the step could not fail and
the committed report was never compared with anything.

Comparing the raw file would be a guaranteed false red anyway, because three
things legitimately differ between the machine the committed copy came from and
a CI runner:

  * the timestamp line (the file is generated),
  * the sha256 of the platform binary in the identity table,
  * the external-oracle columns: the CI job installs `json_repair` and
    `jsonrepair`, while the committed copy was made where one of them was
    absent (`n/a (library not installed)`).

So the report is regenerated here and compared after normalizing exactly those
fields. Everything the gate exists to protect -- the LIWENJSON rows, the corpus
fingerprint and sizes, the rule boundary -- is compared byte for byte.

    python3 code/tests/independent_report_check.py \
        --cli code/_build/native/release/build/cmd/liwenjson/liwenjson.exe
    python3 code/tests/independent_report_check.py --fresh /tmp/report.md \
        --report code/docs/EVAL_INDEPENDENT.md      # compare without running

Exit codes: 0 match, 1 drift, 2 cannot run.
"""
import argparse
import difflib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
CODE = ROOT / "code"
RUNNER = CODE / "tests/eval/run_independent.py"


def split_row(line):
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def is_separator(line):
    return bool(re.match(r"^\|[\s|:-]+\|$", line.strip()))


def normalize_row(header, cells):
    header = [h.strip().lower() for h in header]
    out = list(cells)
    oracle_cols = {
        j for j, h in enumerate(header) if "json_repair" in h or "jsonrepair" in h
    }
    oracle_cols |= {j for j, h in enumerate(header) if "oracle" in h}
    impl_col = next(
        (j for j, h in enumerate(header) if h in ("implementation", "实现")), None
    )
    if oracle_cols and "files" in header:
        # The agreement matrix's file counts are a function of the oracle
        # classifications, so they move when the oracle is installed.
        oracle_cols |= {j for j, h in enumerate(header) if h == "files"}
    row_is_oracle = impl_col is not None and any(
        "jsonrepair" in c.lower() or "json_repair" in c.lower() for c in cells
    )
    for j in range(len(out)):
        if j in oracle_cols:
            out[j] = "<oracle>"
        elif row_is_oracle and j != impl_col:
            out[j] = "<oracle>"
    return out


def normalize(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    out = []
    header = None
    i = 0
    while i < len(lines):
        # The binary identity is build-specific by construction: the sha256
        # names the artefact this run measured, and CI builds a different one.
        # Normalize before table handling so identity-table cells are covered.
        line = re.sub(r"\b[0-9a-f]{64}\b", "<sha256>", lines[i])
        stripped = line.strip()
        if re.match(r"^Generated by .* on .*\.$", stripped):
            out.append("<generated>")
            i += 1
            continue
        # A table header is a `|` line followed by the `| --- |` separator. Data
        # rows are normalized against the header that introduces them.
        if stripped.startswith("|") and i + 1 < len(lines) and is_separator(lines[i + 1]):
            header = split_row(stripped)
            out.append(line)
            out.append(lines[i + 1])
            i += 2
            continue
        if stripped.startswith("|") and header is not None:
            cells = split_row(stripped)
            if len(cells) == len(header):
                cells = normalize_row(header, cells)
            out.append("| " + " | ".join(cells) + " |")
            i += 1
            continue
        if not stripped.startswith("|"):
            header = None
        out.append(line)
        i += 1
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--cli",
        default=str(CODE / "_build/native/release/build/cmd/liwenjson/liwenjson.exe"),
        help="binary to regenerate the report with")
    parser.add_argument(
        "--report", default=str(CODE / "docs/EVAL_INDEPENDENT.md"),
        help="committed report to compare against")
    parser.add_argument(
        "--node-dir", default=None,
        help="directory holding node_modules/jsonrepair (optional)")
    parser.add_argument(
        "--fresh", default=None,
        help="compare this file instead of regenerating (for offline checks)")
    args = parser.parse_args()

    report = Path(args.report)
    if not report.is_file():
        print(f"independent_report_check: cannot run -- {report} is missing", file=sys.stderr)
        return 2

    if args.fresh:
        fresh = Path(args.fresh)
        if not fresh.is_file():
            print(f"independent_report_check: cannot run -- {fresh} is missing", file=sys.stderr)
            return 2
    else:
        cli = Path(args.cli)
        if not cli.is_file():
            print(f"independent_report_check: cannot run -- {cli} is missing", file=sys.stderr)
            return 2
        tmp = Path(tempfile.mkstemp(prefix="independent_", suffix=".md")[1])
        cmd = [sys.executable, str(RUNNER), "--cli", str(cli), "--out", str(tmp)]
        if args.node_dir:
            cmd += ["--node-dir", args.node_dir]
        proc = subprocess.run(cmd, cwd=str(CODE), capture_output=True, text=True)
        if proc.returncode != 0:
            print(proc.stdout[-4000:], file=sys.stderr)
            print(proc.stderr[-4000:], file=sys.stderr)
            print(
                f"independent_report_check: cannot run -- the report generator "
                f"exited {proc.returncode}", file=sys.stderr)
            return 2
        fresh = tmp

    committed = normalize(report)
    produced = normalize(fresh)
    if committed == produced:
        print(
            "independent_report_check: OK — the committed report matches this "
            "build (timestamp, binary sha256 and oracle columns ignored).")
        return 0

    diff = list(
        difflib.unified_diff(
            committed, produced,
            fromfile=f"{report} (committed)",
            tofile=f"{fresh} (this build)",
            lineterm="", n=2))
    print("\n".join(diff[:200]))
    if len(diff) > 200:
        print(f"... and {len(diff) - 200} more diff line(s)")
    print(
        "independent_report_check: FAILED — the committed report no longer "
        "describes what this build produces. Regenerate it with "
        "`python3 tests/eval/run_independent.py`, or explain the change.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
